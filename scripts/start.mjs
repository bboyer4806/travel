import { accessSync, constants, statSync } from "node:fs";
import { dirname, isAbsolute, resolve } from "node:path";

// This entrypoint is for the production container. Never start with a writable
// but disposable container database after a missing or misconfigured mount.
const databasePath = process.env.TRAVEL_DATABASE_PATH;
if (!databasePath || !isAbsolute(databasePath) || dirname(resolve(databasePath)) !== "/data") {
  throw new Error("TRAVEL_DATABASE_PATH must point to a database file directly inside /data.");
}

try {
  if (!statSync("/data/.travel-persistent-storage").isFile()) {
    throw new Error("Storage marker is not a file.");
  }
  accessSync("/data", constants.R_OK | constants.W_OK | constants.X_OK);
} catch (cause) {
  throw new Error(
    "Persistent travel storage is not ready. Mount a writable /data directory with the .travel-persistent-storage marker; see docs/DEPLOYMENT.md.",
    { cause },
  );
}

// Google Sign In cannot work, or would issue insecure cookies, without these server-only settings.
// Values are never logged; see docs/DEPLOYMENT.md.
const missing = ["AUTH_SECRET", "AUTH_URL", "AUTH_GOOGLE_ID", "AUTH_GOOGLE_SECRET", "TRAVEL_OWNER_EMAIL"].filter((name) => !process.env[name]?.trim());
if (missing.length) throw new Error(`Missing sign-in settings: ${missing.join(", ")}. See docs/DEPLOYMENT.md.`);
if (process.env.AUTH_SECRET.length < 32) throw new Error("AUTH_SECRET must be at least 32 characters. Generate one with: openssl rand -base64 33");
if (!URL.canParse(process.env.AUTH_URL) || new URL(process.env.AUTH_URL).protocol !== "https:") {
  throw new Error("AUTH_URL must be the public HTTPS address of the app, for example https://travel.dev.boyersoftware.com.");
}

// Use the Next.js standalone server generated by the build.
await import("../server.js");
